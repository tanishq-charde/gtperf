"""Write the MATLAB port's species table and the reference values its tests compare against.

Run from the repository root:  python matlab/make_reference.py
Both outputs are generated from the Python package, so the two implementations
share one set of coefficients and the MATLAB tests check against Python results.
"""

import tomllib
from pathlib import Path

from gtperf.cli import engine_from_datasheet, turbofan_from_config
from gtperf.cycle import ISO, Ambient
from gtperf.fuel import natural_gas
from gtperf.gas import SPECIES, humid_air

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
ATOMS = ("C", "H", "O", "N", "Ar")


def species_m():
    lines = [
        "function S = gt_species_data()",
        "% NASA 7-coefficient polynomials (GRI-Mech 3.0), molar masses in kg/mol and atom counts",
        "% [C H O N Ar]. Generated by make_reference.py from gtperf.gas.SPECIES: do not edit.",
        "S = struct('name', {}, 'mw', {}, 'atoms', {}, 'tmid', {}, 'high', {}, 'low', {});",
    ]
    fmt = lambda v: " ".join(repr(float(x)) for x in v)  # noqa: E731
    for i, sp in enumerate(SPECIES.values(), start=1):
        atoms = [sp.atoms.get(a, 0) for a in ATOMS]
        lines.append(f"S({i}) = struct('name', '{sp.name}', 'mw', {sp.mw!r}, 'atoms', [{fmt(atoms)}], "
                     f"'tmid', {sp.t_mid!r}, ...")
        lines.append(f"    'high', [{fmt(sp.high)}], ...")
        lines.append(f"    'low', [{fmt(sp.low)}]);")
    lines.append("end")
    return "\n".join(lines) + "\n"


def reference_rows():
    rows = []
    air = humid_air(288.15, 101325.0, 0.6)
    for t in (250.0, 800.0, 1500.0):
        rows += [(f"air_cp_{t:.0f}", air.cp(t)), (f"air_h_{t:.0f}", air.h(t)),
                 (f"air_s_{t:.0f}", air.s(t, 5e5))]
    ng = natural_gas()
    rows += [("ng_lhv", ng.lhv), ("ng_stoich_far", ng.stoichiometric_far(air))]

    _, cal, _ = engine_from_datasheet(ROOT / "examples" / "sgt400_13mw.toml")
    c = cal.cycle
    rows += [("sgt_air_flow", cal.air_flow), ("sgt_tit", c.combustor.t_out),
             ("sgt_turbine_eff", c.hp_turbine.efficiency)]
    for label, amb in (("iso", ISO), ("hot", Ambient(308.15, 101325.0, 0.3))):
        r = c.run(cal.air_flow, amb)
        rows += [(f"sgt_{label}_power", r.electrical_power), (f"sgt_{label}_heat_rate", r.heat_rate),
                 (f"sgt_{label}_fuel_flow", r.fuel_flow), (f"sgt_{label}_t3", r.stations["3"].t),
                 (f"sgt_{label}_t41", r.stations["41"].t), (f"sgt_{label}_p45", r.stations["45"].p),
                 (f"sgt_{label}_t5", r.stations["5"].t)]
    engine, flight = turbofan_from_config(tomllib.loads((ROOT / "examples" / "turbofan_cruise.toml").read_text()))
    r = engine.run(170.0, flight)
    st = r.stations
    rows += [("fan_net_thrust", r.net_thrust), ("fan_tsfc", r.tsfc), ("fan_fuel_flow", r.fuel_flow),
             ("fan_t3", st["3"].t), ("fan_p3", st["3"].p), ("fan_t41", st["41"].t), ("fan_p45", st["45"].p),
             ("fan_p5", st["5"].p), ("fan_t5", st["5"].t), ("fan_core_jet_v", r.core_jet.v),
             ("fan_bypass_jet_v", r.bypass_jet.v), ("fan_v0", r.v0)]
    return rows


def reference_csv():
    return "name,value\n" + "".join(f"{k},{float(v)!r}\n" for k, v in reference_rows())


if __name__ == "__main__":
    (HERE / "gt_species_data.m").write_text(species_m())
    (HERE / "reference_values.csv").write_text(reference_csv())
    print("wrote gt_species_data.m and reference_values.csv")
