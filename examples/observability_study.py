"""Which component faults can the gas-path measurements tell apart? Writes docs/gpa_observability.md.

Earlier versions of the toolkit lumped the two turbines into one "turbine efficiency" and leaned on T3 alone
to separate compressor from turbine faults. This study splits the HP and power turbines and asks how well
the usual industrial package (output, fuel flow, EGT, P3, T3, gas generator speed) isolates each of five
faults, and what improves it:

- adding the power turbine inlet temperature (T45, the inter-turbine thermocouple rake most aeroderivatives
  already carry) and pressure (P45);
- combining the base-load snapshot with one at 60 % load, where the same fault moves the measurements
  differently because the gas generator runs on a different part of its map.

For each configuration it reports the fingerprint similarity of the worst pair of faults, the standard
deviation of each health estimate from one snapshot of field noise, and a Monte Carlo isolation rate: a
single fault of 1 point (efficiency) or 1 % (flow capacity) is injected with field noise, and the best
matching fingerprint must name it.
"""

from collections import Counter
from pathlib import Path

import numpy as np

from gtperf.cli import engine_from_datasheet
from gtperf.fleet import FIELD_NOISE
from gtperf.gpa import (
    EXTENDED_MEASUREMENTS,
    HEALTH_LABELS,
    MEASUREMENT_UNITS,
    MEASUREMENTS,
    SPLIT_HEALTH,
    GasPathAnalysis,
    influence_matrix,
)

ROOT = Path(__file__).resolve().parents[1]
NOISE = dict(zip(MEASUREMENTS, FIELD_NOISE, strict=True)) | {"t45": 3.0, "p45": 0.4}  # K (rake), %
PART_LOAD = 0.6
TRIALS = 2000


def config(name, engine, measurements, part_load=False):
    H = influence_matrix(engine, measurements=measurements, health=SPLIT_HEALTH)
    noise, labels = [NOISE[m] for m in measurements], list(measurements)
    if part_load:
        power = PART_LOAD * engine.run().electrical_power
        keep = [m for m in measurements if m != "power"]  # output is the setting at part load
        Hp = influence_matrix(engine, measurements=keep, health=SPLIT_HEALTH, power=power)
        H = np.vstack([H, Hp])
        noise += [NOISE[m] for m in keep]
        labels += [f"{m}@{100 * PART_LOAD:.0f}%" for m in keep]
    return name, GasPathAnalysis(H, noise, measurements=labels, health=SPLIT_HEALTH)


def isolation_rate(gpa, rng, size=1.0):
    """Fraction of trials in which each injected fault is named, and what it is most often mistaken for."""
    rates, confused = {}, {}
    for j, h in enumerate(SPLIT_HEALTH):
        calls = Counter()
        for _ in range(TRIALS):
            dz = gpa.H[:, j] * rng.choice([-1, 1]) * size + rng.normal(0, gpa.noise)
            calls[gpa.classify(dz)[0][0]] += 1
        rates[h] = calls.pop(h, 0) / TRIALS
        confused[h] = calls.most_common(1)[0][0] if calls else None
    return rates, confused


def main():
    _, _, engine = engine_from_datasheet(ROOT / "examples" / "sgt400_13mw.toml")
    rng = np.random.default_rng(7)
    configs = [
        config("Standard package, base load", engine, MEASUREMENTS),
        config("+ T45", engine, [*MEASUREMENTS, "t45"]),
        config("+ T45 and P45", engine, EXTENDED_MEASUREMENTS),
        config("Standard package, base load + 60 % load", engine, MEASUREMENTS, part_load=True),
        config("+ T45, base load + 60 % load", engine, [*MEASUREMENTS, "t45"], part_load=True),
    ]
    short = {"compressor_flow": "WC", "compressor_eff": "ηC", "hpt_eff": "ηHPT", "turbine_capacity": "WHPT",
             "pt_eff": "ηPT"}
    lines = ["# Gas-path fault isolation: what the measurements can see", "",
             "Generated by `examples/observability_study.py` for the SGT-400 class model. "
             f"Field noise (1σ): {', '.join(f'{m} {v:g} {MEASUREMENT_UNITS[m]}' for m, v in NOISE.items())}.",
             "",
             f"Faults are injected one at a time at ±1 point (efficiency) or ±1 % (flow capacity), {TRIALS} trials "
             "each, with field noise; a trial counts when the best-matching fingerprint (health faults and single "
             "sensor biases) names the injected fault.", "",
             "## Summary", "",
             "| Configuration | Worst pair | Similarity | " + " | ".join(f"σ {short[h]}" for h in SPLIT_HEALTH)
             + " | " + " | ".join(f"Isolated {short[h]}" for h in SPLIT_HEALTH) + " |",
             "|---|---|---:|" + "---:|" * (2 * len(SPLIT_HEALTH))]
    results = {}
    for name, gpa in configs:
        sim = gpa.similarity()
        (a, b), worst = max(sim.items(), key=lambda kv: kv[1])
        std = gpa.health_std()
        rate, confused = isolation_rate(gpa, rng)
        results[name] = (sim, std, rate, confused)
        lines.append(f"| {name} | {short[a]} / {short[b]} | {worst:.3f} | "
                     + " | ".join(f"{s:.2f}" for s in std) + " | "
                     + " | ".join(f"{100 * rate[h]:.0f} %" for h in SPLIT_HEALTH) + " |")
    base_sim = results[configs[0][0]][0]
    lines += ["", "σ is the standard deviation of each health estimate (points or %) from one snapshot by weighted "
              "least squares; above about 1 the parameter is effectively unobservable for a 1-unit fault.", "",
              "## Fingerprint similarity, standard package at base load", "",
              "| | " + " | ".join(short[h] for h in SPLIT_HEALTH) + " |", "|---|" + "---:|" * len(SPLIT_HEALTH)]
    for a in SPLIT_HEALTH:
        cells = []
        for b in SPLIT_HEALTH:
            cells.append("1" if a == b else f"{base_sim.get((a, b), base_sim.get((b, a))):.3f}")
        lines.append(f"| {short[a]} | " + " | ".join(cells) + " |")
    names = [c[0] for c in configs]
    base, both = results[names[0]], results[names[3]]
    t45, p45 = results[names[1]], results[names[2]]
    weak = sorted(SPLIT_HEALTH, key=lambda h: base[2][h])[:2]

    def label(k):
        return f"a {k[7:]} sensor bias" if k.startswith("sensor:") else HEALTH_LABELS[k].split(" (")[0].lower()

    lines += ["", "## Findings", "",
              f"- The compressor and HP turbine efficiency fingerprints are nearly parallel (similarity "
              f"{base[0][('compressor_eff', 'hpt_eff')]:.3f}): both raise fuel flow and EGT together. A 1-point "
              f"fault is still large against field noise, so each is named in {100 * base[2]['compressor_eff']:.0f} % "
              "and {:.0f} % of single snapshots, but smaller faults will be confused more often.".format(
                  100 * base[2]["hpt_eff"]),
              f"- The faults the standard package isolates worst at one load are {short[weak[0]]} "
              f"({100 * base[2][weak[0]]:.0f} %, most often mistaken for {label(base[3][weak[0]])}) and "
              f"{short[weak[1]]} ({100 * base[2][weak[1]]:.0f} %, mistaken for {label(base[3][weak[1]])}). They look "
              "like an instrument drift because each moves essentially one measurement.",
              f"- Adding T45 changes little here ({short[weak[1]]} {100 * t45[2][weak[1]]:.0f} %): with a 3 K rake "
              f"uncertainty it carries little that EGT and speed do not. P45 tightens every estimate "
              f"(σ {short['pt_eff']} {base[1][4]:.2f} to {p45[1][4]:.2f}) "
              "but does not change which faults are confused.",
              f"- A second snapshot at {100 * PART_LOAD:.0f} % load with the existing instruments is what works: "
              f"{short[weak[0]]} rises to {100 * both[2][weak[0]]:.0f} % and {short[weak[1]]} to "
              f"{100 * both[2][weak[1]]:.0f} %, and every σ falls. The gas generator runs at a different corrected "
              "speed at part load, so the fingerprints rotate relative to each other and to the sensor biases. In "
              "service this is a pair of points from the same day's dispatch, which the part-load fleet monitor "
              "provides.", "",
              "## Limits", "",
              "- Linear, single-fault isolation on a synthetic engine; multiple simultaneous faults need the weighted "
              "least-squares estimate (`GasPathAnalysis.estimate`) and benefit from a prior.",
              "- The T45 and P45 noise levels are assumptions for a field rake; their real values come from the "
              "instrument budget."]
    out = ROOT / "docs" / "gpa_observability.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
